/**
 * Единый источник правды по цифрам компании.
 *
 * Раньше они были разбросаны по метатегам, JSON-LD и секциям и успели
 * разъехаться: на /projects стояло «18 лет опыта», в описании организации —
 * «с 2005 года» при foundingDate 2014. Любое число о компании берём отсюда.
 */

/** Год основания. ООО «ВЛАДЕН» основано в 2014 году в Адлере. */
export const FOUNDED_YEAR = 2014;

/**
 * Полных лет на рынке. Считается на момент сборки — значит обновляется
 * сама при каждом деплое, а не живёт хардкодом до следующей правки руками.
 */
export const YEARS_ON_MARKET = new Date().getFullYear() - FOUNDED_YEAR;

/**
 * Сдано объектов. Правится руками — по договорённости с заказчиком,
 * не считается автоматически. До сведения к одному значению по сайту
 * гуляли три числа: 200+, 300+ и 369+.
 */
export const OBJECTS_DONE = 369;

/** Готовая строка вида «369+». */
export const OBJECTS_PHRASE = `${OBJECTS_DONE}+`;

/** Число городов присутствия. */
export const CITIES = 6;

/** Доля довольных клиентов по отзывам, %. */
export const SATISFACTION = 98;

/**
 * Склонение слова «год» под число: 12 лет, 21 год, 22 года.
 * Нужно, потому что YEARS_ON_MARKET меняется и «12 лет» однажды станет «21 год».
 */
export function yearsWord(n: number = YEARS_ON_MARKET): string {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return "лет";
  switch (n % 10) {
    case 1:
      return "год";
    case 2:
    case 3:
    case 4:
      return "года";
    default:
      return "лет";
  }
}

/** Готовая строка вида «12 лет». */
export const YEARS_PHRASE = `${YEARS_ON_MARKET} ${yearsWord()}`;
