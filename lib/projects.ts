export interface GalleryImage {
  src: string;
  alt: string;
  /** Подпись под превью — используется в отчётах авторского надзора */
  caption?: string;
}

export interface GalleryGroup {
  title: string;
  images: GalleryImage[];
}

export interface RoomSchedule {
  floor: string;
  total: string;
  rooms: { name: string; area: string }[];
}

export interface ProjectStage {
  title: string;
  text: string;
}

export interface Project {
  slug: string;
  title: string;
  /** Короткий тип объекта — бейдж на карточке */
  tag: string;
  location: string;
  /** Год для карточки и сортировки */
  year: string;
  /** Подпись статуса на странице объекта */
  status: string;
  area: string;
  /** Обложка карточки; null — рисуем плейсхолдер */
  cover: string | null;
  /** Текст на карточке в портфолио */
  cardDesc: string;
  /** Вводный абзац на странице объекта */
  lead: string;
  subtitle: string;
  stats: { value: string; label: string }[];
  features: string[];
  galleryGroups?: GalleryGroup[];
  schedule?: RoomSchedule[];
  stages?: ProjectStage[];
  /** Ссылка на страницу авторского надзора внизу кейса */
  showNadzorCta?: boolean;
  seo: {
    title: string;
    description: string;
    keywords: string[];
  };
}

/** Плоский список всех фото объекта — для лайтбокса и счётчиков */
export function flatGallery(project: Project): GalleryImage[] {
  return (project.galleryGroups ?? []).flatMap((g) => g.images);
}

